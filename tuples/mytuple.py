 # Ordered and unchangeable Duplicates allowed - Faster access
mytuple = ("apple", "banana", "cherry")
print(mytuple)

# access the tuple item 
print(mytuple[1])


thistuple = ("apple", "banana", "cherry")
for x in thistuple:
  print(x)

# Join the tuples
tuple1 = ("a", "b" , "c")
tuple2 = (1, 2, 3)

tuple3 = tuple1 + tuple2
print(tuple3)